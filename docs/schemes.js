/**
 * Generate step shades for a family
 */
window.generateStepShades = function(familyIndex, numSteps) {
  const families = window.MOVE_COLOR_FAMILIES;
  const family = families[familyIndex % families.length];
  if (numSteps <= 1) {
    return [family[Math.floor(family.length / 2)]];
  }
  const indices = [];
  for (let i = 0; i < numSteps; i++) {
    indices.push(Math.round(i * (family.length - 1) / Math.max(1, numSteps - 1)));
  }
  return indices.map(idx => family[idx]);
};

/**
 * Format label according to labelling scheme:
 * - 'number-letter': e.g. M1-S1 -> 1a, M2-S1B -> 2b, M1-S0 -> 1, HEADING -> H, OTHER -> O
 * - 'simplified': e.g. M1-S1 -> 1.1, M2-S1B -> 2.1B
 * - 'step-only': e.g. M1-S1 -> S1, M2-S1B -> S1B
 * - 'original': e.g. M1-S1
 */
window.formatLabelText = function(labelId, mode = 'number-letter') {
  if (!labelId) return '';
  const labelStr = String(labelId).trim();
  const upper = labelStr.toUpperCase();

  if (['HEADING', 'HEAD', 'H'].includes(upper)) return 'H';
  if (['OTHER', 'OTHERS', 'O'].includes(upper)) return 'O';
  if (['TITLE', 'T'].includes(upper)) return 'T';

  const normMode = mode.toLowerCase().replace(/_/g, '-');

  // Match Move-Step: e.g. M1-S1, M2-S1B, M1_S2, Move1 Step1, M1S1A
  const msMatch = labelStr.match(/[Mm](\d+)[-_\s]*[Ss](\d+)([A-Za-z]*)/);
  if (msMatch) {
    const moveNum = msMatch[1];
    const stepNum = msMatch[2];
    const subLetter = msMatch[3].toUpperCase();

    if (normMode === 'step-only') {
      return `S${stepNum}${subLetter}`;
    } else if (normMode === 'simplified') {
      return `${moveNum}.${stepNum}${subLetter}`;
    } else if (normMode === 'number-letter') {
      const stepIdx = parseInt(stepNum, 10);
      if (stepIdx === 0) {
        return subLetter ? `${moveNum}${subLetter.toLowerCase()}` : `${moveNum}`;
      }
      let letter = (stepIdx >= 1 && stepIdx <= 26) ? String.fromCharCode(96 + stepIdx) : String(stepIdx);
      if (subLetter) {
        letter = subLetter.toLowerCase();
      }
      return `${moveNum}${letter}`;
    } else if (normMode === 'original') {
      return `M${moveNum}-S${stepNum}${subLetter}`;
    }
  }

  // Match Number-Letter notation: e.g. 1a, 1b, 2a, 2c, 1A, 2B, 3d
  const nlMatch = labelStr.match(/^(\d+)([A-Za-z]+)$/);
  if (nlMatch) {
    const moveNum = nlMatch[1];
    const letterStr = nlMatch[2].toLowerCase();
    const stepIdx = (letterStr.length === 1 && letterStr >= 'a' && letterStr <= 'z') ? (letterStr.charCodeAt(0) - 96) : 0;

    if (normMode === 'number-letter') {
      return `${moveNum}${letterStr}`;
    } else if (normMode === 'simplified') {
      return `${moveNum}.${stepIdx > 0 ? stepIdx : letterStr}`;
    } else if (normMode === 'step-only') {
      return `S${stepIdx > 0 ? stepIdx : letterStr.toUpperCase()}`;
    } else if (normMode === 'original') {
      return `M${moveNum}-S${stepIdx > 0 ? stepIdx : letterStr.toUpperCase()}`;
    }
  }

  // Match Decimal notation: e.g. 1.1, 1.2, 2.1, 2.4
  const decMatch = labelStr.match(/^(\d+)\.(\d+)([A-Za-z]*)$/);
  if (decMatch) {
    const moveNum = decMatch[1];
    const stepNum = parseInt(decMatch[2], 10);
    const subLetter = decMatch[3].toLowerCase();
    const letter = (stepNum >= 1 && stepNum <= 26) ? String.fromCharCode(96 + stepNum) : String(stepNum);
    const effectiveLetter = subLetter || letter;

    if (normMode === 'number-letter') {
      return `${moveNum}${effectiveLetter}`;
    } else if (normMode === 'simplified') {
      return `${moveNum}.${stepNum}${subLetter}`;
    } else if (normMode === 'step-only') {
      return `S${stepNum}${subLetter.toUpperCase()}`;
    } else if (normMode === 'original') {
      return `M${moveNum}-S${stepNum}${subLetter.toUpperCase()}`;
    }
  }

  // Match Step only: e.g. S1, S2A
  const sMatch = labelStr.match(/^[Ss](\d+)([A-Za-z]*)$/);
  if (sMatch) {
    const stepNum = sMatch[1];
    const subLetter = sMatch[2].toUpperCase();
    if (normMode === 'step-only') {
      return `S${stepNum}${subLetter}`;
    } else if (normMode === 'simplified') {
      return `${stepNum}${subLetter}`;
    } else if (normMode === 'number-letter') {
      const stepIdx = parseInt(stepNum, 10);
      let letter = (stepIdx >= 1 && stepIdx <= 26) ? String.fromCharCode(96 + stepIdx) : String(stepIdx);
      if (subLetter) letter = subLetter.toLowerCase();
      return letter;
    }
  }

  // Match Move only: e.g. M1, M2
  const mMatch = labelStr.match(/^[Mm](\d+)$/);
  if (mMatch) {
    const moveNum = mMatch[1];
    if (normMode === 'step-only') return `M${moveNum}`;
    return moveNum;
  }

  return labelStr;
};

/**
 * Return #000000 or #ffffff contrast text color based on relative luminance
 */
window.getContrastTextColor = function(hexColor) {
  if (!hexColor || !hexColor.startsWith('#')) return '#ffffff';
  try {
    const hex = hexColor.replace('#', '');
    if (hex.length === 6) {
      const r = parseInt(hex.substring(0, 2), 16);
      const g = parseInt(hex.substring(2, 4), 16);
      const b = parseInt(hex.substring(4, 6), 16);
      const lum = 0.299 * r + 0.587 * g + 0.114 * b;
      return lum > 165 ? '#111827' : '#ffffff';
    }
  } catch (e) {}
  return '#ffffff';
};

/**
 * Parse custom scheme formatted as lines of `label;move;step`
 */
window.parseCustomScheme = function(content) {
  const lines = String(content).split('\n');
  const movesMap = {};
  const moveNames = {};

  for (let line of lines) {
    line = line.trim();
    if (!line || line.startsWith('#') || line.toLowerCase().startsWith('label;move;step')) continue;

    const parts = line.split(';').map(p => p.trim());
    let labelId = '', moveName = '', stepName = '';
    if (parts.length >= 3) {
      labelId = parts[0];
      moveName = parts[1];
      stepName = parts[2];
    } else if (parts.length === 2) {
      labelId = parts[0];
      moveName = parts[1];
      stepName = parts[0];
    } else {
      continue;
    }

    const moveId = moveName.toLowerCase().replace(/\s+/g, '_');
    if (!movesMap[moveId]) {
      movesMap[moveId] = [];
      moveNames[moveId] = moveName;
    }
    movesMap[moveId].push({
      id: labelId,
      name: `${labelId}: ${stepName}`,
      title: stepName,
      description: ''
    });
  }

  const moves = [];
  let moveIdx = 0;
  for (const moveId in movesMap) {
    const stepsRaw = movesMap[moveId];
    const shades = window.generateStepShades(moveIdx, stepsRaw.length);
    const steps = stepsRaw.map((s, idx) => ({
      ...s,
      color: shades[idx]
    }));
    moves.push({
      id: moveId,
      move_number: moveIdx + 1,
      name: moveNames[moveId],
      steps: steps
    });
    moveIdx++;
  }

  // Add other
  moves.push({
    id: 'other',
    name: 'Other',
    steps: [
      { id: 'HEADING', name: 'Section heading', title: 'Heading', description: 'Section header marker', color: '#000000' },
      { id: 'OTHER', name: 'Others/ Metadata', title: 'Other', description: 'Miscellaneous', color: '#9ca3af' }
    ]
  });

  return {
    key: 'custom',
    source: 'Custom Scheme',
    section: 'Custom',
    citation: 'User-defined rhetorical scheme',
    moves: moves
  };
};
